import { describe, expect, it } from 'vitest'

import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'

const read = (relativePath: string) => readFileSync(resolve(process.cwd(), relativePath), 'utf8')

describe('LuckRead H5 blue design system', () => {
  it('defines shared blue design tokens and applies them to shared frontend surfaces', () => {
    const styles = read('src/app/(frontend)/styles.css')
    const login = read('src/app/(frontend)/login/login.css')
    const register = read('src/app/(frontend)/register/register.css')
    const publish = read('src/app/(frontend)/publish/publish.css')

    expect(styles).toContain('--lr-blue-600: #2563eb')
    expect(styles).toContain('--lr-h5-bg: #f5f9ff')
    expect(styles).toContain('.lr-auth-shell')
    expect(styles).toContain('.content-browse')
    expect(styles).toContain('.content-detail')
    expect(styles).not.toContain('.my-subscriptions')
    expect(styles).toContain('.lr-publish-shell')

    expect(login).toContain('#102a56')
    expect(register).toContain('#2563eb')
    expect(publish).toContain('#2563eb')
    const subscriptionsPage = read('src/app/(frontend)/me/subscriptions/MySubscriptionsPage.tsx')
    const subscriptionsRoute = read('src/app/(twitter-clone)/me/subscriptions/page.tsx')
    expect(subscriptionsPage).not.toContain('subscriptions.css')
    expect(subscriptionsPage).toContain('border-b border-light-border')
    expect(subscriptionsRoute).toContain('TwitterCloneSecondaryPageLayout')
    expect(subscriptionsRoute).toContain('active="subscriptions"')
    const shortsRoute = read('src/app/(frontend)/shorts/page.tsx')
    expect(shortsRoute).toContain('TwitterCloneSecondaryPageLayout')
    expect(shortsRoute).toContain('active="videos"')
    expect(shortsRoute).toContain('<ShortVideoFeed />')
    expect(shortsRoute).not.toContain('shorts.css')
    const publicFollowList = read('src/app/(frontend)/users/[userId]/UserFollowList.tsx')
    const publicFollowersRoute = read('src/app/(frontend)/users/[userId]/followers/page.tsx')
    const publicFollowingRoute = read('src/app/(frontend)/users/[userId]/following/page.tsx')
    expect(publicFollowList).toContain('TwitterCloneSecondaryPageLayout')
    expect(publicFollowList).toContain("active={isFollowers ? 'connections' : 'following'}")
    expect(publicFollowList).toContain('presentation="x-timeline"')
    expect(publicFollowList).not.toContain('content-detail-card')
    expect(publicFollowersRoute).toContain('UserFollowList')
    expect(publicFollowingRoute).toContain('UserFollowList')
    const publicProfileHeader = read('src/app/(frontend)/users/[userId]/TwitterCloneProfileHeader.tsx')
    const publicProfileNav = read('src/app/(frontend)/users/[userId]/TwitterCloneProfileNav.tsx')
    const publicProfilePage = read('src/app/(frontend)/users/[userId]/page.tsx')
    expect(publicProfileHeader).toContain('h-36 bg-light-line-reply xs:h-48 sm:h-52')
    expect(publicProfileHeader).not.toContain('creator-profile-hero')
    expect(publicProfileNav).toContain('main-tab dark-bg-tab')
    expect(publicProfileNav).not.toContain('creator-profile-tabs')
    expect(publicProfilePage).not.toContain('creator-profile-button')
    expect(styles).not.toContain('.creator-profile-hero')
    expect(styles).not.toContain('.creator-profile-tabs')
    const passwordPage = read('src/app/(frontend)/me/password/page.tsx')
    expect(passwordPage).toContain('TwitterCloneSecondaryPageLayout')
    expect(passwordPage).toContain('active="editProfile"')
    expect(passwordPage).toContain("'/api/v1/auth/password/change'")
    expect(passwordPage).toContain('MIN_PASSWORD_LENGTH = 15')
    expect(passwordPage).toContain('MAX_PASSWORD_LENGTH = 128')
    expect(passwordPage).not.toContain('style={{')
    const sessionsPage = read('src/app/(frontend)/me/sessions/page.tsx')
    expect(sessionsPage).toContain('TwitterCloneSecondaryPageLayout')
    expect(sessionsPage).toContain('active="editProfile"')
    expect(sessionsPage).toContain("'/api/v1/auth/sessions?'")
    expect(sessionsPage).toContain("'/api/v1/auth/sessions/'")
    expect(sessionsPage).toContain('session-revoke-')
    expect(sessionsPage).not.toContain('style={{')
    const creatorApplication = read('src/app/(frontend)/creator-application/CreatorApplicationClient.tsx')
    expect(creatorApplication).toContain('TwitterCloneSecondaryPageLayout')
    expect(creatorApplication).toContain('showLanguageToggle={false}')
    expect(creatorApplication).toContain("'/api/v1/creator-applications'")
    expect(creatorApplication).toContain("'creator-apply:'")
    expect(creatorApplication).not.toContain('styles.header')
    const shareLanding = read('src/app/(frontend)/s/[shareId]/page.tsx')
    expect(shareLanding).toContain('TwitterCloneSecondaryPageLayout')
    expect(shareLanding).toContain('active="explore"')
    expect(shareLanding).toContain("'/api/v1/shares/'")
    expect(shareLanding).toContain("router.replace('/content/'")
    expect(shareLanding).not.toContain('style={{')
    const usernameProfileRoute = read('src/app/(frontend)/[username]/page.tsx')
    expect(usernameProfileRoute).toContain('TwitterCloneSecondaryPageLayout')
    expect(usernameProfileRoute).toContain('active="profile"')
    expect(usernameProfileRoute).toContain("'/api/v1/users/by-username/'")
    expect(usernameProfileRoute).toContain("return <UserProfilePage params={Promise.resolve({ userId })} />")
    expect(usernameProfileRoute).toContain('Loading author profile…')
    expect(usernameProfileRoute).not.toContain('<main className="content-detail"')
  })

  it('does not introduce another frontend page directory for the blue redesign', () => {
    const styles = read('src/app/(frontend)/styles.css')
    expect(styles).toContain('LuckRead Blue H5 design system')
  })
})
