import { describe, expect, it } from 'vitest'
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { isValidRevenueCatAppId } from '../../src/subscription/w07-subscription-client.js'

const openapi = readFileSync(resolve(process.cwd(), '../../contracts/openapi/v1/openapi.yaml'), 'utf8')
const apiInventory = JSON.parse(readFileSync(resolve(process.cwd(), '../../contracts/api/api-inventory.v1.json'), 'utf8'))

describe('v1 subscription adapter', () => {
  it('accepts canonical RevenueCat app IDs and rejects controls or non-canonical values', () => {
    expect(isValidRevenueCatAppId('luckread-ios-production')).toBe(true)
    expect(isValidRevenueCatAppId('luckread-android-production')).toBe(true)
    for (const value of ['', ' luckread-ios-production', 'luckread-ios-production ', 'luckread\nproduction', 'luckread\u0000production', 'x'.repeat(256)]) {
      expect(isValidRevenueCatAppId(value)).toBe(false)
    }
  })
  const route = readFileSync(resolve(process.cwd(), 'src/app/api/v1/memberships/subscriptions/[[...segments]]/route.ts'), 'utf8')
  const mySubscriptionsPage = readFileSync(resolve(process.cwd(), 'src/app/(frontend)/me/subscriptions/MySubscriptionsPage.tsx'), 'utf8')
  const plansRoute = readFileSync(resolve(process.cwd(), 'src/app/api/v1/plans/route.ts'), 'utf8')
  const creatorPlansRoute = readFileSync(resolve(process.cwd(), 'src/app/api/v1/membership/plans/route.ts'), 'utf8')
  const creatorMembershipPlans = readFileSync(resolve(process.cwd(), 'src/app/(frontend)/creator-center/CreatorMembershipPlans.tsx'), 'utf8')
  const creatorStudio = readFileSync(resolve(process.cwd(), 'src/app/(frontend)/creator-center/CreatorStudio.tsx'), 'utf8')
  const publishPlanRoute = readFileSync(resolve(process.cwd(), 'src/app/api/v1/membership/plans/[planId]/publish/route.ts'), 'utf8')
  const lifecyclePlanRoute = readFileSync(resolve(process.cwd(), 'src/app/api/v1/membership/plans/[planId]/lifecycle/route.ts'), 'utf8')
  const updatePlanRoute = readFileSync(resolve(process.cwd(), 'src/app/api/v1/membership/plans/[planId]/route.ts'), 'utf8')
  const w08CreatorClient = readFileSync(resolve(process.cwd(), 'src/auth/w08-creator-client.ts'), 'utf8')
  const w08Worker = readFileSync(resolve(process.cwd(), '../W08-creator/src/worker.ts'), 'utf8')
  const w08Casl = readFileSync(resolve(process.cwd(), '../W08-creator/src/authz/casl-policy.ts'), 'utf8')
  const w06Worker = readFileSync(resolve(process.cwd(), '../W06-governance/src/index.ts'), 'utf8')
  const w07Worker = readFileSync(resolve(process.cwd(), '../W07-subscription-commerce/src/index.ts'), 'utf8')
  const w06Client = readFileSync(resolve(process.cwd(), 'src/moderation/w06-moderation-client.ts'), 'utf8')
  const client = readFileSync(resolve(process.cwd(), 'src/subscription/w07-subscription-client.ts'), 'utf8')
  const wrangler = readFileSync(resolve(process.cwd(), 'wrangler.jsonc'), 'utf8')

  it('routes plan discovery through W07 and keeps the existing inventory path', () => {
    expect(openapi).toContain('operationId: getPlans')
    expect(apiInventory.domains.subscription_entitlement_payment.endpoint_groups).toContain('GET /v1/plans')
    expect(plansRoute).toContain('resolveCookieSubscriptionPrincipal')
    expect(plansRoute).toContain("pathname: '/plans' + url.search")
    expect(plansRoute).toContain("method: 'GET'")
    expect(plansRoute).toContain('callW07Subscription')
    expect(plansRoute).not.toContain('export async function POST')
  })

  it('requires W08 CASL plus active creator identity before forwarding owner-scoped plan management', () => {
    expect(creatorPlansRoute).toContain("membership.plan.create.own")
    expect(creatorPlansRoute).toContain("membership.plan.read.own")
    expect(creatorPlansRoute).toContain("'/internal/authz/check-permission'")
    expect(creatorPlansRoute).toContain('(value as { data?: { decision?: unknown } }).data?.decision')
    expect(creatorPlansRoute).toContain("'/internal/creator/self'")
    expect(creatorPlansRoute).toContain('(value as { data?: { creatorId?: unknown } }).data?.creatorId')
    expect(w08Worker).toContain('return json({ creatorId: creator.creator_id, status: \'ACTIVE\' })')
    expect(creatorPlansRoute).toContain("verifiedCreatorId: creatorId")
    expect(w08CreatorClient).toContain("'/internal/creator/self'")
    expect(w08CreatorClient).toContain("'/internal/authz/check-permission'")
    expect(creatorPlansRoute).not.toContain('body.creatorId')
    expect(creatorPlansRoute).not.toContain('body.ownerId')
    expect(creatorPlansRoute).toContain('request.body.getReader()')
    expect(creatorPlansRoute).toContain('byteLength > 16_384')
    expect(creatorPlansRoute).toContain("new TextDecoder('utf-8', { fatal: true })")
    expect(creatorPlansRoute).not.toContain('await request.text()')
  })

  it('does not return plan creation success until W06 confirms the immutable audit event', () => {
    expect(creatorPlansRoute).toContain('callW06MembershipPlanAudit')
    expect(creatorPlansRoute).toContain("eventId: 'evt_mpl_created_' + plan.planId")
    expect(creatorPlansRoute).toContain('priceMinor: plan.priceMinor')
    expect(creatorPlansRoute).toContain('currency: plan.currency')
    expect(creatorPlansRoute).toContain('billingInterval: plan.billingInterval')
    expect(creatorPlansRoute).toContain("action?: unknown }).action !== 'membership.plan.created'")
    expect(creatorPlansRoute).toContain('Membership plan audit was not durably confirmed')
    expect(w06Client).toContain("'/internal/audit-events/membership-plan-created'")
    expect(w06Worker).toContain("action: 'membership.plan.created'")
    expect(w06Worker).toContain('AUDIT_EVENT_PERSISTENCE_FAILED')
    expect(w06Worker).toContain('AUDIT_EVENT_CONFLICT')
  })

  it('publishes membership plans through CASL, W07 version CAS, and a durable W06 audit', () => {
    expect(openapi).toContain('operationId: publishOwnMembershipPlan')
    expect(apiInventory.domains.subscription_entitlement_payment.endpoint_groups)
      .toContain('POST /v1/membership/plans/{planId}/publish')
    expect(publishPlanRoute).toContain("'membership.plan.publish.own'")
    expect(publishPlanRoute).toContain("'/internal/authz/check-permission'")
    expect(publishPlanRoute).toContain("'/internal/creator/self'")
    expect(publishPlanRoute).toContain("'/membership/plans/' + encodeURIComponent(planId) + '/publish'")
    expect(publishPlanRoute).toContain("request.headers.get('If-Match')")
    expect(publishPlanRoute).toContain('callW06MembershipPlanPublishRequestAudit')
    expect(w06Client).toContain("'/internal/audit-events/membership-plan-publish-requested'")
    expect(publishPlanRoute.indexOf('callW06MembershipPlanPublishRequestAudit'))
      .toBeLessThan(publishPlanRoute.indexOf('const w07Response = await callW07Subscription'))
    expect(publishPlanRoute).toContain('callW06MembershipPlanPublishAudit')
    expect(publishPlanRoute).toContain("eventId: 'evt_mpl_published_' + plan.planId + '_v' + plan.version")
    expect(publishPlanRoute).toContain("action?: unknown }).action !== 'membership.plan.published'")
    expect(publishPlanRoute).toContain('Membership plan publish audit was not durably confirmed')
    expect(w06Client).toContain("'/internal/audit-events/membership-plan-published'")
    expect(w06Worker).toContain("url.pathname === '/internal/audit-events/membership-plan-publish-requested'")
    expect(w06Worker).toContain("action: 'membership.plan.publish_requested'")
    expect(w06Worker).toContain("url.pathname === '/internal/audit-events/membership-plan-published'")
    expect(w06Worker).toContain("action: 'membership.plan.published'")
    expect(w08Casl).toContain("grant('membership.plan.publish.own', 'MembershipPlan', selfOwnerCondition(subjectId))")
  })


  it('updates creator plan terms through owner authorization, immutable W07 version CAS, and durable W06 audits', () => {
    expect(openapi).toContain('operationId: updateOwnMembershipPlan')
    expect(apiInventory.domains.subscription_entitlement_payment.endpoint_groups)
      .toContain('PUT /v1/membership/plans/{planId}')
    expect(updatePlanRoute).toContain("'membership.plan.update.own'")
    expect(updatePlanRoute).toContain("'/internal/authz/check-permission'")
    expect(updatePlanRoute).toContain("'/internal/creator/self'")
    expect(updatePlanRoute).toContain("method: 'PUT'")
    expect(updatePlanRoute).toContain("request.headers.get('If-Match')")
    expect(updatePlanRoute).toContain("request.headers.get('Idempotency-Key')")
    expect(updatePlanRoute).toContain('callW06MembershipPlanUpdateRequestAudit')
    expect(w06Client).toContain("'/internal/audit-events/membership-plan-update-requested'")
    expect(updatePlanRoute.indexOf('const intentValue')).toBeLessThan(updatePlanRoute.indexOf('const w07Response = await callW07Subscription'))
    expect(updatePlanRoute).toContain('callW06MembershipPlanUpdateAudit')
    expect(updatePlanRoute).toContain("'evt_mpl_updated_' + planId + '_v' + plan.version")
    expect(w06Client).toContain("'/internal/audit-events/membership-plan-updated'")
    expect(w06Worker).toContain("action: 'membership.plan.update_requested'")
    expect(w06Worker).toContain("action: 'membership.plan.updated'")
    expect(w08Casl).toContain("grant('membership.plan.update.own', 'MembershipPlan', selfOwnerCondition(subjectId))")
  })

  it('pauses/resumes/retires an owned plan through CASL, W07 lifecycle CAS and W06 audits', () => {
    expect(openapi).toContain('operationId: transitionOwnMembershipPlanLifecycle')
    expect(apiInventory.domains.subscription_entitlement_payment.endpoint_groups)
      .toContain('POST /v1/membership/plans/{planId}/lifecycle')
    expect(lifecyclePlanRoute).toContain("'membership.plan.lifecycle.own'")
    expect(lifecyclePlanRoute).toContain("'/internal/authz/check-permission'")
    expect(lifecyclePlanRoute).toContain("'/internal/creator/self'")
    expect(lifecyclePlanRoute).toContain('callW06MembershipPlanLifecycleRequestAudit')
    expect(lifecyclePlanRoute.indexOf('callW06MembershipPlanLifecycleRequestAudit'))
      .toBeLessThan(lifecyclePlanRoute.indexOf('const w07Response = await callW07Subscription'))
    expect(lifecyclePlanRoute).toContain("'/membership/plans/' + encodeURIComponent(planId) + '/lifecycle'")
    expect(lifecyclePlanRoute).toContain('callW06MembershipPlanLifecycleAudit')
    expect(lifecyclePlanRoute).toContain("['pause', 'resume', 'retire']")
    expect(lifecyclePlanRoute).toContain("'membership.plan.retired'")
    expect(w06Client).toContain("'/internal/audit-events/membership-plan-lifecycle-requested'")
    expect(w06Client).toContain("'/internal/audit-events/membership-plan-lifecycle-changed'")
    expect(w06Worker).toContain("url.pathname === '/internal/audit-events/membership-plan-lifecycle-requested'")
    expect(w06Worker).toContain("url.pathname === '/internal/audit-events/membership-plan-lifecycle-changed'")
    expect(w08Casl).toContain("grant('membership.plan.lifecycle.own', 'MembershipPlan', selfOwnerCondition(subjectId))")
  })

  it('contracts creator plan permissions and server-controlled draft fields', () => {
    expect(openapi).toContain('operationId: listOwnMembershipPlans')
    expect(openapi).toContain('operationId: createOwnMembershipPlanDraft')
    expect(apiInventory.domains.subscription_entitlement_payment.endpoint_groups).toContain('GET /v1/membership/plans')
    expect(apiInventory.domains.subscription_entitlement_payment.endpoint_groups).toContain('POST /v1/membership/plans')
    expect(creatorPlansRoute).toContain("pathname: '/membership/plans' + url.search")
    expect(creatorPlansRoute).toContain("pathname: '/membership/plans'")
  })

  it('validates the complete W07 draft envelope and immutable v1 result before auditing', () => {
    expect(creatorPlansRoute).toContain("typeof envelope.requestId !== 'string'")
    expect(creatorPlansRoute).toContain("typeof plan.updatedAt !== 'string'")
    expect(creatorPlansRoute).toContain("typeof plan.version !== 'number' || plan.version !== 1")
    expect(creatorPlansRoute).toContain('plan.etag !==')
    expect(creatorPlansRoute).toContain('lr-plan-v1')
    expect(creatorPlansRoute).toContain("typeof plan.replayed !== 'boolean'")
    expect(creatorPlansRoute).toContain('!Array.isArray(plan.benefits)')
    expect(creatorPlansRoute).toContain('new Set(plan.benefits).size !== plan.benefits.length')
  })

  it('binds W01 to the canonical W07 subscription authority', () => {
    expect(wrangler).toContain('W07_SUBSCRIPTION')
    expect(wrangler).toContain('luckread-w07')
    expect(client).toContain('W07_SUBSCRIPTION')
  })

  it('uses the cookie-backed principal and internal service transport', () => {
    expect(client).toContain('resolveCookieContentPrincipal')
    expect(client).toContain("X-LuckRead-Caller': 'W01'")
    expect(client).toContain("X-LuckRead-Transport-Version': '1.0'")
    expect(client).toContain('X-LuckRead-Principal-User-Id')
    expect(client).toContain('Idempotency-Key')
    expect(client).toContain('If-Match')
    expect(route).toContain('callW07Subscription')
  })

  it('fails closed on subscription writes until verified billing synchronization is available', () => {
    const writeGuard = route.indexOf("if (request.method === 'POST')")
    const transportCall = route.indexOf('callW07Subscription({ request, pathname, method:')
    expect(writeGuard).toBeGreaterThan(-1)
    expect(transportCall).toBeGreaterThan(writeGuard)
    expect(route).toContain("'SERVICE_UNAVAILABLE'")
    expect(route).toContain('verified payment-provider synchronization flow')
    expect(route).not.toContain("requireHeader(request, 'Idempotency-Key')")
    expect(route).not.toContain("requireHeader(request, 'If-Match')")
  })

  it('keeps subscription management read-only while verified provider synchronization is gated', () => {
    expect(route).toContain('Subscription writes are disabled until a verified payment-provider synchronization flow is available.')
    expect(mySubscriptionsPage).toContain('mutationsUnavailable')
    expect(mySubscriptionsPage).not.toContain("transition(item, 'pause')")
    expect(mySubscriptionsPage).not.toContain("transition(item, 'resume')")
    expect(mySubscriptionsPage).not.toContain("transition(item, 'cancel')")
    expect(mySubscriptionsPage).toContain('payment-provider synchronization')
    expect(mySubscriptionsPage).toContain("fetchJson<ListResponse>('/api/v1/memberships/subscriptions?limit=20&page='")
  })

  it('exposes audited WEB trial start and cancellation through W01 W08 W07 and W06', () => {
    expect(openapi).toContain('operationId: startMembershipTrial')
    expect(openapi).toContain('operationId: cancelMembershipTrial')
    expect(apiInventory.domains.subscription_entitlement_payment.endpoint_groups)
      .toContain('POST /v1/memberships/subscriptions/trial')
    expect(apiInventory.domains.subscription_entitlement_payment.endpoint_groups)
      .toContain('POST /v1/memberships/subscriptions/{subscriptionId}/cancel-trial')
    expect(route).toContain("parts[0] === 'trial'")
    expect(route).toContain("parts[1] === 'cancel-trial'")
    expect(route).toContain("'subscription.start_trial'")
    expect(route).toContain("'subscription.cancel'")
    expect(route).toContain('callW06SubscriptionTrialAudit')
    expect(route).toContain("'/internal/audit-events/subscription-trial'")
    expect(w07Worker).toContain('startWebMembershipTrial')
    expect(w07Worker).toContain('cancelWebMembershipTrial')
    expect(w07Worker).toContain('getMembershipTrialDetails')
    expect(w08Casl).toContain("grant('subscription.start_trial', 'Subscription', selfOwnerCondition(subjectId))")
    expect(w08Casl).toContain("grant('subscription.cancel', 'Subscription', selfOwnerCondition(subjectId))")
  })

  it('allows creators to configure immutable trial duration on plan create and revision', () => {
    expect(openapi).toContain('trialDays: { type: integer, minimum: 0, maximum: 90')
    expect(creatorMembershipPlans).toContain('trialDays: number')
    expect(creatorMembershipPlans).toContain('setTrialDays')
    expect(creatorMembershipPlans).toContain('trialDays,')
    expect(creatorMembershipPlans).toContain('trialDays: editTrialDays')
    expect(creatorPlansRoute).toContain('Number.isSafeInteger(plan.trialDays)')
    expect(updatePlanRoute).toContain("'trialDays'")
    expect(updatePlanRoute).toContain('fields.trialDays')
    expect(publishPlanRoute).toContain('trialDays: plan.trialDays')
    expect(w06Worker).toContain('trialDays: input.trialDays')
  })

  it('shows trial provenance in the subscription page and only offers WEB trial cancellation', () => {
    expect(mySubscriptionsPage).toContain("'PENDING' | 'TRIALING' | 'ACTIVE'")
    expect(mySubscriptionsPage).toContain("item.trial.source === 'WEB'")
    expect(mySubscriptionsPage).toContain("'/cancel-trial'")
    expect(mySubscriptionsPage).toContain("'If-Match': item.etag")
    expect(mySubscriptionsPage).toContain("item.trial.source !== 'WEB'")
    expect(mySubscriptionsPage).toContain('manageStoreTrial')
    expect(mySubscriptionsPage).toContain('trialEndsAt')
    expect(mySubscriptionsPage).toContain("item.trial.status === 'PAYMENT_FAILED'")
  })

  it('declares the existing subscription collection list operation', () => {
    expect(openapi).toContain('operationId: listMembershipSubscriptions')
    expect(apiInventory.domains.subscription_entitlement_payment.endpoint_groups)
      .toContain('GET /v1/memberships/subscriptions')
    expect(route).toContain("parts.length === 0 && method === 'GET'")
  })

  it('connects creator studio to owner-scoped membership plan management without claiming paid checkout is live', () => {
    expect(creatorStudio).toContain("import CreatorMembershipPlans from './CreatorMembershipPlans'")
    expect(creatorStudio).toContain('<CreatorMembershipPlans locale={locale} />')
    expect(creatorMembershipPlans).toContain("'/api/v1/membership/plans?'")
    expect(creatorMembershipPlans).toContain("'/api/v1/membership/plans'")
    expect(creatorMembershipPlans).toContain("'/publish'")
    expect(creatorMembershipPlans).toContain("'/lifecycle'")
    expect(creatorMembershipPlans).toContain("'If-Match': plan.etag")
    expect(creatorMembershipPlans).toContain("'Idempotency-Key': key")
    expect(creatorMembershipPlans).toContain("method: 'PUT'")
    expect(creatorMembershipPlans).toContain("'/api/v1/membership/plans/' + encodeURIComponent(plan.planId)")
    expect(creatorMembershipPlans).toContain("data.data.status !== plan.status")
    expect(creatorMembershipPlans).toContain("setMessage(labels.successRevision)")
    expect(creatorMembershipPlans).toContain("Existing subscriptions keep their previous version.")
    expect(creatorMembershipPlans).toContain("plan.status !== 'RETIRED'")
    expect(creatorMembershipPlans).toContain("action: 'publish' | 'pause' | 'resume' | 'retire'")
    expect(creatorMembershipPlans).toContain('paid checkout stays unavailable')
    expect(creatorMembershipPlans).toContain("plan.status === 'PAUSED'")
    expect(creatorMembershipPlans).toContain("RETIRED: '已退役'")
  })

  it('exposes the canonical subscription reads and audited scheduled plan-change path', () => {
    expect(route).toContain("/memberships/subscriptions")
    expect(route).toContain("parts.length === 0 && method === 'GET'")
    expect(route).toContain("['cancel', 'pause', 'resume', 'change-plan', 'upgrade', 'cancel-trial']")
    expect(route).toContain("action: 'subscription.change_plan'")
    expect(route).toContain('callW06SubscriptionPlanChangeRequestAudit')
    expect(route).toContain('callW06SubscriptionPlanChangeAudit')
    expect(route).toContain('callW07Subscription')
    expect(route).not.toContain('entitlement')
  })

  it('keeps cancel, pause, resume, and create writes closed while allowing only CASL-audited scheduled plan changes', () => {
    const scheduleBranch = route.indexOf('if (isPlanChangeRequest)')
    const writeGuard = route.indexOf("if (request.method === 'POST')", scheduleBranch)
    expect(scheduleBranch).toBeGreaterThan(-1)
    expect(writeGuard).toBeGreaterThan(scheduleBranch)
    expect(route).toContain('Subscription writes are disabled until a verified payment-provider synchronization flow is available.')
    expect(route.indexOf('callW06SubscriptionPlanChangeRequestAudit')).toBeLessThan(
      route.indexOf("pathname: operation.pathname")
    )
  })
})
